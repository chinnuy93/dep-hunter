from __future__ import annotations

from dephunter.core.models import Confidence
from dephunter.core.util import format_duration
from dephunter.reporting.base import (
    ReportContext,
    display_ref_location,
    md_escape,
)

_ORDER = [
    Confidence.CONFIRMED,
    Confidence.HIGH_CONFIDENCE,
    Confidence.CANDIDATE,
    Confidence.INSUFFICIENT_EVIDENCE,
]


def render(context: ReportContext) -> str:
    lines: list[str] = []
    line = lines.append
    line("> **DEP-HUNTER** · Passive dependency-confusion analysis")
    line("> Authorized-scope evidence · static indicators only")
    line("")
    line(f"# Dep-Hunter dependency confusion report — {md_escape(context.program)}")
    line("")
    line(f"- **Scan:** #{context.scan_id} ({md_escape(context.scan.get('status'))})")
    line(f"- **Phase:** {md_escape(context.scan.get('phase'))}")
    line(f"- **Generated:** {context.generated_at}")
    line(f"- **Tool version:** {context.tool_version}")
    if context.runtime:
        line(
            f"- **Run time:** {format_duration(context.runtime.get('duration_seconds'))}  "
            f"| **Scan progress:** {context.progress_percent}%"
        )
    if context.scan.get("scope", {}).get("authorization"):
        line(f"- **Authorization basis:** {md_escape(context.scan['scope']['authorization'])}")
    line("")
    line("## Summary")
    line("")
    counts = context.confidence_counts()
    line("| Class | Findings |")
    line("|---|---:|")
    for confidence in _ORDER:
        line(f"| {confidence.value} | {counts.get(confidence.value, 0)} |")
    line(f"| **Total** | **{len(context.findings)}** |")
    line("")
    deps = context.stats.get("dependencies", 0)
    registry_counts = context.stats.get("registry_checks", {})
    line(f"Dependencies parsed: **{deps}**. Registry checks: **{registry_counts.get('total', 0)}**.")
    weak = sum(1 for finding in context.findings if finding.get("classification") == Confidence.INSUFFICIENT_EVIDENCE.value)
    if weak:
        line(f"{weak} insufficient-evidence assessment(s) are excluded from the findings sections.")
    line("")

    _execution(lines, context)

    scope = context.scan.get("scope", {})
    line("## Scope")
    line("")
    web = scope.get("web") or []
    line(f"- Web targets: {', '.join(str(item.get('url')) for item in web) if web else 'none'}")
    github = scope.get("github") or {}
    line(f"- GitHub: orgs={github.get('orgs') or []}, repos={github.get('repos') or []}")
    gitlab = scope.get("gitlab") or {}
    line(f"- GitLab: projects={gitlab.get('projects') or []}")
    registries = scope.get("registries") or {}
    line(f"- Registries: {', '.join(registries.get('enabled') or [])}")
    line(f"- Registry query limit: {registries.get('query_limit', 'unknown')}")
    line("")

    line("## Method")
    line("")
    line("Passive collection only: public web assets and public repository contents were fetched with GET/HEAD;")
    line("manifests, lockfiles, JavaScript, source maps, and CI configuration were parsed as data. Public registry")
    line("metadata was queried with authoritative 200/404 semantics. No package was published, installed, reserved,")
    line("or executed; no callback or credential collection was performed.")
    line("")

    line("## Findings")
    line("")
    if not context.findings:
        line("No findings met the configured minimum classification.")
        line("")
    for index, finding in enumerate(context.sorted_findings(), 1):
        _finding(lines, index, finding, context)
        line("")

    line("## Limitations")
    line("")
    line("- Static evidence cannot prove that a target's build or install path selects an attacker-controlled package.")
    line("- Target-side confirmation requires separate written authorization and an isolated environment.")
    line("- Registry absence can change; package statuses are point-in-time and cached responses are not live.")
    line("- Publisher and repository metadata are self-reported by package maintainers.")
    line("")
    line("_Generated by Dep-Hunter. Findings are static indicators, not proof of compromise._")
    line("")
    return "\n".join(lines)


def _execution(lines: list[str], context: ReportContext) -> None:
    if not context.runtime:
        return
    lines.append("## Execution")
    lines.append("")
    lines.append(
        f"Total run time: **{format_duration(context.runtime.get('duration_seconds'))}**. "
        f"Scan progress: **{context.progress_percent}%**."
    )
    lines.append("")
    phases = context.phase_seconds
    if phases:
        lines.append("| Phase | Seconds |")
        lines.append("|---|---:|")
        for phase, seconds in phases.items():
            lines.append(f"| {md_escape(phase)} | {seconds:.2f} |")
        lines.append("")


def _finding(lines: list[str], index: int, finding: dict, context: ReportContext) -> None:
    classification = str(finding.get("classification"))
    lines.append(f"### {index}. [{classification}] {md_escape(finding.get('title') or finding.get('name'))}")
    lines.append("")
    lines.append(
        f"- **Ecosystem:** {md_escape(finding.get('ecosystem'))}  "
        f"| **Package:** `{md_escape(finding.get('name'))}`  "
        f"| **Score:** {finding.get('score')}  "
        f"| **CWE:** {md_escape(finding.get('cwe_primary'))} / {md_escape(finding.get('cwe_secondary'))}"
    )
    evidence = finding.get("evidence") or {}
    registry = evidence.get("registry") or {}
    lines.append(
        f"- **Registry:** {md_escape(registry.get('status'))} "
        f"(HTTP {registry.get('http_status') if registry.get('http_status') is not None else 'n/a'}) "
        f"| latest={md_escape(registry.get('latest_version') or 'unknown')} "
        f"| publisher={md_escape(registry.get('publisher') or 'not exposed')}"
    )
    resolution = finding.get("resolution") or {}
    lines.append(
        f"- **Routing:** public={md_escape(resolution.get('public_routing'))} "
        f"| private={md_escape(resolution.get('private_routing'))} "
        f"| public evidence={bool(resolution.get('public_resolution_evidence'))} "
        f"| mixed provenance={bool(resolution.get('mixed_provenance'))}"
    )
    lines.append("")
    lines.append("**Why it was flagged**")
    lines.append("")
    for reason in finding.get("reasons") or []:
        lines.append(f"- {md_escape(reason)}")
    if not finding.get("reasons"):
        lines.append("- No reasons recorded.")
    lines.append("")

    refs = evidence.get("refs") or []
    if refs:
        lines.append("**Evidence locations**")
        lines.append("")
        lines.append("| Source | Location | Version | Resolved URL |")
        lines.append("|---|---|---|---|")
        for ref in refs[:25]:
            lines.append(
                f"| {md_escape(ref.get('source_kind'))} "
                f"| {md_escape(display_ref_location(ref))} "
                f"| {md_escape(ref.get('version_constraint') or '')} "
                f"| {md_escape(ref.get('resolved_url') or '')} |"
            )
        lines.append("")
        if len(refs) > 25:
            lines.append(f"_{len(refs) - 25} additional occurrence(s) omitted._")
            lines.append("")

    facts = evidence.get("facts") or []
    if facts:
        lines.append("**Registry configuration evidence**")
        lines.append("")
        lines.append("| Fact | Value | Location |")
        lines.append("|---|---|---|")
        for fact in facts[:20]:
            location = fact.get("file_path") or fact.get("source_url") or ""
            if fact.get("line"):
                location = f"{location}:{fact['line']}"
            lines.append(
                f"| {md_escape(fact.get('fact_type'))} "
                f"| {md_escape(fact.get('value'))} "
                f"| {md_escape(location)} |"
            )
        lines.append("")

    missing = finding.get("missing") or []
    if missing:
        lines.append("**Missing evidence / required confirmation**")
        lines.append("")
        for item in missing:
            lines.append(f"- {md_escape(item)}")
        lines.append("")

    verification = context.verification_for(finding)
    if verification:
        lines.append(f"**Static verification:** {verification.verdict}")
        lines.append("")
        for check in verification.checks:
            lines.append(f"- {check.status}: {md_escape(check.name)} — {md_escape(check.detail)}")
        lines.append("")
        lines.append(f"> {md_escape(verification.allowed_claim)}")
        lines.append("")
